function generateSparklineSVG(points, isPositive = true) {
  if (!points || points.length < 2) {
    points = [10, 12, 11, 14, 15, 17, 18];
  }
  const width = 70;
  const height = 24;
  const strokeColor = isPositive ? "#16a34a" : "#dc2626";
  const fillColor = isPositive ? "rgba(22, 163, 74, 0.10)" : "rgba(220, 38, 38, 0.10)";

  const min = Math.min(...points);
  const max = Math.max(...points);
  const range = max - min || 1;

  const coords = points.map((val, idx) => {
    const x = (idx / (points.length - 1)) * width;
    const y = height - ((val - min) / range) * (height - 8) - 4;
    return `${x.toFixed(1)},${y.toFixed(1)}`;
  });

  // Smooth path construction
  let pathD = `M ${coords[0]}`;
  for (let i = 1; i < coords.length; i++) {
    pathD += ` L ${coords[i]}`;
  }

  const areaD = `${pathD} L ${width},${height} L 0,${height} Z`;

  return `
    <svg class="sparkline-svg" viewBox="0 0 ${width} ${height}" xmlns="http://www.w3.org/2000/svg" style="width: 70px; height: 24px; flex-shrink: 0;">
      <path d="${areaD}" fill="${fillColor}" />
      <path d="${pathD}" fill="none" stroke="${strokeColor}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" />
    </svg>
  `;
}

async function renderMandiPrices() {
  const container = document.getElementById("mandi-prices-container");
  if (!container) return;

  let liveCommodities = null;
  let metadata = null;

  try {
    // Try fetching live analytics generated by the ML engine
    const res = await fetch("data/mandi_live_analytics.json?t=" + Date.now());
    if (res.ok) {
      const data = await res.json();
      liveCommodities = data.commodities || [];
      metadata = data.metadata || {};
    }
  } catch (err) {
    console.warn("Could not load mandi_live_analytics.json directly, trying API...", err);
  }

  if (!liveCommodities || liveCommodities.length === 0) {
    try {
      const res = await fetch("/api/mandi/forecasts");
      if (res.ok) {
        const data = await res.json();
        liveCommodities = data.commodities || [];
        metadata = data.metadata || {};
      }
    } catch (err) {
      console.warn("Could not load /api/mandi/forecasts", err);
    }
  }

  // If live data is available, build curated list of key agricultural crops
  if (liveCommodities && liveCommodities.length > 0) {
    const keyCropNames = ["Tomato", "Onion", "Potato", "Paddy", "Cotton", "Chilli", "Wheat", "Turmeric"];
    const displayList = [];

    keyCropNames.forEach(targetName => {
      const found = liveCommodities.find(c => c.commodity.toLowerCase() === targetName.toLowerCase());
      if (found) {
        displayList.push(found);
      }
    });

    // If less than 4 found, fill with first few commodities
    if (displayList.length < 4) {
      liveCommodities.slice(0, 6).forEach(c => {
        if (!displayList.some(d => d.commodity === c.commodity)) {
          displayList.push(c);
        }
      });
    }

    container.innerHTML = displayList.slice(0, 5).map(item => {
      const modal = item.modal_price || 1500;
      const perKg = (modal / 100).toFixed(2);
      const perQt = modal.toLocaleString("en-IN");
      const pct = item.change_1w_pct !== undefined ? item.change_1w_pct : (item.forecast ? item.forecast.pct_change_7d : 0);
      const isUp = pct >= 0;
      const arrow = isUp ? "↑" : "↓";
      const trendClass = isUp ? "trend-up" : "trend-down";
      const trendPoints = item.history_7d && item.history_7d.length >= 2 ? item.history_7d : [modal * 0.95, modal * 0.97, modal * 0.96, modal * 0.98, modal * 0.99, modal];
      const sparkline = generateSparklineSVG(trendPoints, isUp);

      return `
        <div class="mandi-row" style="display: grid; grid-template-columns: 1fr 1.4fr 1fr; align-items: center; padding: 10px 8px; border-bottom: 1px solid var(--border-subtle, #e2e8f0);">
          <div class="mandi-crop-name" style="font-weight: 700; color: #1e293b;">
            ${item.commodity}
            <div style="font-size: 0.72rem; color: #64748b; font-weight: normal;">${item.market ? item.market.replace(/ APMC.*| Mandi.*/i, '') : 'APMC'}</div>
          </div>
          <div class="mandi-price" style="font-weight: 700; color: #0f172a; font-size: 0.88rem;">
            ₹ ${perKg} /kg <br>
            <span style="font-size: 0.75rem; color: #64748b; font-weight: 600;">(₹ ${perQt} /Qt)</span>
          </div>
          <div class="mandi-trend ${trendClass}" style="display: flex; align-items: center; justify-content: flex-end; gap: 6px; font-weight: 700; font-size: 0.82rem;">
            <span>${arrow} ${Math.abs(pct).toFixed(1)}%</span>
            ${sparkline}
          </div>
        </div>
      `;
    }).join("");

    // Also dynamically update the "Price Forecast & Insights" widget on dashboard
    updateDashboardForecastCard(liveCommodities);
    return;
  }

  // Fallback to static data if offline
  if (typeof farmerData !== "undefined" && farmerData.mandiPrices) {
    container.innerHTML = farmerData.mandiPrices.map(item => {
      const isUp = item.direction === "up";
      const arrow = isUp ? "↑" : "↓";
      const trendClass = isUp ? "trend-up" : "trend-down";
      const sparkline = generateSparklineSVG(item.trendPoints, isUp);

      return `
        <div class="mandi-row" style="display: grid; grid-template-columns: 1fr 1.4fr 1fr; align-items: center; padding: 10px 8px; border-bottom: 1px solid var(--border-subtle, #e2e8f0);">
          <div class="mandi-crop-name" style="font-weight: 700;">${item.crop}</div>
          <div class="mandi-price" style="font-weight: 700;">${item.currentPrice}</div>
          <div class="mandi-trend ${trendClass}" style="display: flex; align-items: center; justify-content: flex-end; gap: 6px; font-weight: 700; font-size: 0.82rem;">
            <span>${arrow} ${item.trendPercent}</span>
            ${sparkline}
          </div>
        </div>
      `;
    }).join("");
  }
}

function updateDashboardForecastCard(commodities) {
  if (!commodities || commodities.length === 0) return;

  // Find Tomato or highest confidence gainer
  let featured = commodities.find(c => c.commodity.toLowerCase() === "tomato");
  if (!featured) {
    featured = commodities.find(c => c.forecast && c.forecast.pct_change_7d > 0) || commodities[0];
  }

  if (!featured || !featured.forecast) return;

  const f = featured.forecast;
  const pct = f.pct_change_7d;
  const sign = pct >= 0 ? "+" : "";
  const pctStr = `${sign}${pct.toFixed(1)}% *`;
  const currPerKg = (f.current_price / 100).toFixed(2);
  const targetPerKg = (f.target_price_7d / 100).toFixed(2);
  const currPerQt = f.current_price.toLocaleString("en-IN");
  const targetPerQt = f.target_price_7d.toLocaleString("en-IN");

  const cropNameEl = document.querySelector(".forecast-crop-name");
  const pctEl = document.querySelector(".forecast-percentage");
  const subEl = document.querySelector(".forecast-sub");
  const descEl = document.querySelector(".forecast-description");
  const actionBtn = document.querySelector(".forecast-box .btn");

  if (cropNameEl) cropNameEl.textContent = featured.commodity;
  if (pctEl) {
    pctEl.textContent = pctStr;
    pctEl.style.color = pct >= 0 ? "#15803d" : "#dc2626";
  }
  if (subEl) subEl.textContent = `(Expected 7-Day Target: ₹ ${targetPerKg}/kg | ₹ ${targetPerQt}/Qt)`;
  
  if (descEl) {
    const rationale = featured.advisory && featured.advisory.rationale 
      ? featured.advisory.rationale 
      : `AI Holt-Winters model indicates rising demand. Wholesale prices projected to rise from ₹${currPerKg}/kg (₹${currPerQt}/Qt) to ₹${targetPerKg}/kg (₹${targetPerQt}/Qt) with ${f.confidence_pct || 95}% confidence.`;
    descEl.textContent = rationale;
  }

  if (actionBtn) {
    actionBtn.onclick = () => {
      window.location.href = "market-insights.html";
    };
  }
}

document.addEventListener("DOMContentLoaded", renderMandiPrices);
